/** Сколько последних реплик передаётся модели: окно контекста у неё небольшое */
const HISTORY_LIMIT = 8
const MESSAGE_LIMIT = 1500
/** Сколько последних записей истории попадает в контекст */
const RECORDS_LIMIT = 12

const clip = (text: string, limit: number) => (text.length > limit ? `${text.slice(0, limit)}…` : text)

/** Данные автомобиля и истории в виде короткого текста для модели. Только то, что есть в приложении */
export function describeCar(car: Car, records: ServiceRecord[]): string {
  const lines = [
    `Автомобиль: ${car.make} ${car.model}, ${car.year} года выпуска.`,
    `Пробег: ${car.mileage} км.`,
    car.generation ? `Поколение или код кузова: ${car.generation}.` : '',
    car.body ? `Тип кузова: ${BODY_LABELS[car.body].toLowerCase()}.` : '',
    car.engine ? `Двигатель: ${ENGINE_LABELS[car.engine].toLowerCase()}${car.fuel ? `, топливо ${car.fuel}` : ''}.` : '',
  ].filter(Boolean)
  const recent = [...records].sort((a, b) => b.date.localeCompare(a.date)).slice(0, RECORDS_LIMIT)
  if (recent.length === 0) {
    lines.push('История обслуживания: записей нет.')
  } else {
    lines.push(`История обслуживания (последние ${recent.length} из ${records.length}):`)
    for (const record of recent) {
      lines.push(`- ${record.date}: ${clip(record.title, 80)} (${CATEGORY_LABELS[record.category].toLowerCase()}), пробег ${record.mileage} км, ${record.cost} тенге${record.comment ? `. ${clip(record.comment, 120)}` : ''}`)
    }
  }
  lines.push('Других данных об автомобиле нет. Не дополняй их догадками.')
  return lines.join('\n')
}

/** Сообщения для модели: инструкции, данные пользователя (если он их дал) и последние реплики */
export function buildMessages(history: ChatMessage[], carContext: string | null): ChatMessage[] {
  const system = carContext ? `${SYSTEM_PROMPT}\n\nДанные пользователя (получены из его личного кабинета):\n${carContext}` : SYSTEM_PROMPT
  return [{ role: 'system', content: system }, ...history.slice(-HISTORY_LIMIT).map((message) => ({ ...message, content: clip(message.content, MESSAGE_LIMIT) }))]
}
