// Правила, по которым вопрос считается опасным. От модели они не зависят: на такие вопросы
// отвечает заранее написанный текст, а не ИИ.
//
// Это набор слов и сочетаний, а не понимание смысла. Он ловит прямые названия систем, частые опечатки
// и распространённые косвенные описания («педаль проваливается», «стрелка в красной зоне»),
// но не может поймать всё: вопрос, заданный необычными словами, дойдёт до модели. Поэтому предупреждение
// о том, что ИИ не заменяет сервис, показывается на странице всегда.
//
// Файл намеренно без зависимостей: правила проверяются отдельным скриптом на наборе примеров.

/**
 * danger — описана неисправность или ситуация, при которой ехать опасно;
 * care   — вопрос о системе безопасности без признаков неисправности (обслуживание, выбор деталей);
 * none   — обычный вопрос, отвечает модель.
 */
export type SafetyClass = 'danger' | 'care' | 'none'

/** Текст для сравнения: без регистра, «ё» = «е», без знаков, растянутые буквы сжаты («тормоооз» → «тормоз») */
const normalize = (text: string) =>
  ` ${text
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/(.)\1{2,}/g, '$1')
    .replace(/[^a-zа-я0-9]+/g, ' ')
    .trim()} `

// Системы, от которых зависит безопасность. Гласные в корнях допускают частые опечатки: «тармоза», «тормаза».
const SYSTEM = new RegExp(
  [
    // тормоза
    'т[оа]рм[оа]?[зжсш]',
    'торм[оа]ж',
    'колодк',
    'суппорт',
    'ручник',
    'стояночн',
    ' abs ',
    ' абс ',
    'brake',
    'tormo[zs]',
    // рулевое управление
    ' рул[ьяюеи]',
    ' рулем',
    'рулев',
    'баранк',
    ' гур ',
    ' гура ',
    ' эур ',
    'гидроусилит',
    'электроусилит',
    'steering',
    // подушки и ремни безопасности
    'подушк\\S* безоп',
    'подушк\\S* (сработ|выстрел|раскр|ламп)',
    'airbag',
    'аирбаг',
    'эирб[еэ]г',
    'эйрб[еэ]г',
    ' srs ',
    ' срс ',
    'ремн\\S* безоп',
    'ремень безоп',
    // колёса и подвеска
    'шаров',
    'ступиц',
    'колес\\S* .{0,24}(отвал|откру|болта|люфт|отлет)',
    '(отвал|откру|отлет)\\S* .{0,24}колес',
    '(гайк|болт)\\S* колес',
    'рычаг\\S* подвес',
  ].join('|'),
)

// Ситуации, опасные сами по себе, какая бы система ни была названа
const EMERGENCY = new RegExp(
  [
    // дым, огонь, запахи
    ' д[ыи]м',
    'задым',
    ' пар .{0,12}(капот|двигател|мотор)',
    '(из под|под) капот\\S* .{0,16}(пар|валит|идет)',
    'пожар',
    'возгор',
    'загорел\\S* (машин|авто|двигател|мотор|проводк|под капот)',
    ' горит (машин|авто|двигател|мотор|проводк)',
    'искрит',
    ' искры',
    'плавится',
    'оплавил',
    '(запах|пахнет|воняет|несет|завонял)\\S* .{0,24}(бензин|топлив|соляр|газ|гар|горел|жжен|пален|проводк|дым)',
    // перегрев
    'перегре',
    ' кипит',
    'закипел',
    'вскипел',
    'стрелк\\S* .{0,24}(красн|зашкал|в конц)',
    'температур\\S* .{0,24}(красн|зашкал|растет|поднял|высок|максим)',
    '(антифриз|тосол|охлажда)\\S* .{0,24}(уход|вытек|теч|кипит|убыва|пропал)',
    // давление масла и красные лампы
    'давлени\\S* масл',
    'масленк',
    'красн\\S* (ламп|значок|индикатор|лампочк)',
    // потеря управления и торможения
    'не тормоз',
    'не останавлива',
    'не остановит',
    'отказал',
    'не слушается',
    'заклинил',
    'клинит',
    ' занос',
    'заносит',
    'увод\\S* в сторон',
    'тянет в сторон',
    'потерял\\S* управлени',
    'педал\\S* .{0,24}(провал|в пол|мягк|ватн|уходит)',
    'провал\\S* .{0,16}педал',
    // утечки
    'теч\\S* .{0,20}(тормоз|топлив|бензин)',
    '(тормоз|топлив|бензин)\\S* .{0,20}(теч|капа|вытек)',
    'утечк',
    // подушки
    'подушк\\S* (сработ|выстрел|раскр)',
  ].join('|'),
)

// Слова о неисправности: вместе с названием системы безопасности означают опасную тему
const SYMPTOM =
  /скрип|скреж|стук|стуч|шум|гул |гуд|вибр|бьет|биени|тянет|мягк|провал|ватн|туг|тяжел|люфт|не работа|перестал|плохо|слаб|горит|загорел|ламп|мига|теч|капа|свист|хруст|щелч|заед|клин|дерга|болта|греет|нагрев|пахнет|запах|слом|отказ|трещ|износ|стер|можно ли ездить|опасно|доеду|доехать|ошибк|не держ|не крут|не поворач|откру|отвал|отлет|skrip|soft|squeal|noise|leak|fail|stuck|loose/

export function classifyQuestion(question: string): SafetyClass {
  const text = normalize(question)
  if (EMERGENCY.test(text)) return 'danger'
  if (!SYSTEM.test(text)) return 'none'
  return SYMPTOM.test(text) ? 'danger' : 'care'
}

